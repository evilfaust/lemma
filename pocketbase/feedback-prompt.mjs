// Черновик обратной связи ученику по итогам интенсива (v3.9.243) — промпт и
// разбор ответа LLM. Чистый модуль: без сети, под тестами
// `ege-tasks/src/__tests__/intensiveFeedback.test.js`.
//
// 🚨 Имён в LLM не отправляем: вместо имени модель пишет {ИМЯ}, обращение
// («Ксюша», «Лёня») подставляет клиент. В данных — только пол, оценки,
// проценты, названия и описания работ.

export const NAME_TOKEN = '{ИМЯ}';

const MAX_EXAMPLES = 12000;
const MAX_DATA = 16000;

export const FEEDBACK_RULES = `Ты — учитель математики. Пишешь ученику короткую обратную связь по итогам интенсива (несколько дней подряд по одной теме, в день несколько работ, в конце зачётная работа). Пиши так, как принято на кафедре.

ПРАВИЛА:
1. Начни с обращения «${NAME_TOKEN},» и говори с учеником на «ты». Настоящих имён не придумывай — только ${NAME_TOKEN}.
2. ПЕРВОЕ ПРЕДЛОЖЕНИЕ — ВСЕГДА О ХОРОШЕМ. Возьми настоящую сильную сторону из раздела «сильные_стороны» (лучший день, работа выше среднего по группе, домашние задания, прогресс к концу, лучший результат на зачёте, пришёл(ла) на зачёт несмотря на пропуски). Даже если итог слабый, начни с того, что получилось, — и не с пропусков, а с того, что ученик сделал. Не выдумывай того, чего нет в данных.
3. Дальше — как ученик работал в течение интенсива (ровно / неровно, по дням) и как написал зачёт: соответствует ли зачёт работе на интенсиве.
4. Затем — что доработать. Тему называй ТОЛЬКО словами из полей «что_проверяла» / «что_проверял» и из разделов «сильные_стороны» / «слабые_места». Где написано «не описано» — тему НЕ называй и НЕ угадывай, говори общо («задания последнего дня», «домашние задания»).
5. «Молодец» — только если заслужено (итог 5 или 4+, сильный зачёт, заметный прогресс).
6. Если «пересдача» = «да» — закончи приглашением: «Ждём тебя на пересдачу» или «Разбирайся, готовься и сдавай зачёт». Если «пересдача» = «нет» — о пересдаче НЕ пиши вообще, даже если зачёт слабый.
7. Рейтинг — только из поля «рейтинг»: «Первый рейтинг.» / «Второй рейтинг.» / «Третий рейтинг.» последним предложением. Если «рейтинг» = «нет» — о рейтинге не пиши ни слова (в образцах он есть не у всех).
8. Не называй баллы, проценты, оценки и даты. Дни — словами: «в первый день», «в последний день». «Лучший результат в группе на зачёте» — можно, если место первое.
9. Род глаголов — по полу из данных (работал / работала).
10. 2–4 предложения, не больше 70 слов. Тон честный и поддерживающий, без канцелярита, без лести, без восклицательных знаков подряд.
11. Не пиши общих фраз про итоговую оценку («итог соответствует твоей работе» и т.п.) — только конкретика.
12. Обороты кафедры: «отмечаем…», «к сожалению…», «сумел(а) собраться к зачёту», «Обрати внимание на…», «Тебе надо доразобраться с…», «Молодец».

Ответ — только текст обратной связи, без кавычек, заголовков и пояснений.`;

/** Сообщения для chat/completions. data — объект ученика (без имён), examples — образцы стиля. */
export function buildFeedbackMessages(data, examples = '') {
  const ex = String(examples || '').trim().slice(0, MAX_EXAMPLES);
  const system = ex
    ? `${FEEDBACK_RULES}\n\nОБРАЗЦЫ СТИЛЯ КАФЕДРЫ (имена заменены на ${NAME_TOKEN}; оценки перед текстом — «зачёт / итог»):\n${ex}`
    : FEEDBACK_RULES;
  const json = JSON.stringify(data ?? {}, null, 1).slice(0, MAX_DATA);
  return [
    { role: 'system', content: system },
    { role: 'user', content: `Данные ученика по интенсиву:\n${json}\n\nНапиши обратную связь.` },
  ];
}

const RATING_SENTENCE = /\s*[^.!?]*(первый|второй|третий|четвёртый|пятый|шестой)\s+рейтинг[^.!?]*[.!?]?/gi;
const RETAKE_SENTENCE = /\s*[^.!?]*(пересдач|сдавай зач[её]т|пересдавай)[^.!?]*[.!?]?/gi;

/**
 * Ответ модели → чистый текст черновика: без кавычек и markdown, обращение —
 * токеном. Модель иногда подставляет «Имя,»/«[Имя],» вместо токена или
 * пропускает обращение — поправляем. Страховка поверх промпта: без рейтинга в
 * данных фраза «…рейтинг» вырезается, без пересдачи — приглашение на неё
 * (модель подхватывает их из образцов).
 * data — те же данные ученика, что ушли в модель.
 */
export function cleanFeedback(raw, data = null) {
  let t = String(raw ?? '').trim();
  t = t.replace(/^```[a-z]*\s*|```$/gi, '').trim();
  t = t.replace(/^["«„“]+|["»“”]+$/g, '').trim();
  t = t.replace(/\*\*/g, '');
  // Варианты токена, которые модели пишут сами.
  t = t.replace(/\{\s*(имя|ИМЯ|Имя|name|NAME)\s*\}|\[(имя|ИМЯ|Имя)\]|<(имя|ИМЯ|Имя)>/g, NAME_TOKEN);
  if (!t) return '';
  if (data && (!data.рейтинг || data.рейтинг === 'нет')) t = t.replace(RATING_SENTENCE, '').trim();
  if (data && data.пересдача === 'нет') t = t.replace(RETAKE_SENTENCE, '').trim();
  if (!t) return '';
  if (!t.startsWith(NAME_TOKEN)) {
    // «Имя, …» / «Ученик, …» в начале — это обращение, меняем на токен.
    const m = t.match(/^(Имя|Ученик|Ученица)\s*,\s*/);
    t = m ? `${NAME_TOKEN}, ${t.slice(m[0].length)}` : `${NAME_TOKEN}, ${t.charAt(0).toLowerCase()}${t.slice(1)}`;
  }
  return t.replace(/\s+/g, ' ').trim();
}
