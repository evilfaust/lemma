/**
 * Уровни и метки экзаменов для разделов устного счёта.
 *
 * Уровень меняет числа и запись ВНУТРИ типа задания, а не набор типов:
 * «логарифм степени» на разминке — `log₂ 8`, на экзамене — `log₅ 60 − log₅ 2,4`.
 * Метка экзамена (О6, Б14, П8) говорит, к какому заданию готовит тип; у одного
 * типа их может быть несколько — `√a·√b` нужен и в ОГЭ №8, и в базе №16.
 *
 * Решения пользователя 05.10.2026: переключатель уровня вместо отдельного
 * блока «простых», метки с номером задания, ручные примеры из «Решу» остаются
 * образцами уровня «Как на экзамене».
 */

export const ORAL_LEVELS = [
  { value: 1, label: 'Разминка',        hint: 'Табличные значения, одно действие, маленькие числа' },
  { value: 2, label: 'Как на экзамене', hint: 'Формат и числа заданий ОГЭ и ЕГЭ' },
  { value: 3, label: 'Сложнее',         hint: 'Больше действий, неудобные числа, комбинация приёмов' },
];

export const DEFAULT_LEVEL = 2;

/** Уровень из настроек листа: старые листы уровня не знают — «как на экзамене». */
export function levelOf(settings) {
  const v = Number(settings?.level);
  return v === 1 || v === 2 || v === 3 ? v : DEFAULT_LEVEL;
}

