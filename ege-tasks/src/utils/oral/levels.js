/** Метки типа строкой-массивом (карта хранит и строку, и массив). */
export function tagsOf(examMap, cat) {
  const t = examMap?.[cat];
  if (!t) return [];
  return Array.isArray(t) ? t : [t];
}

/** Есть ли у раздела типы этого экзамена — иначе кнопку фильтра не показываем. */
export function hasExam(examMap, exam) {
  return Object.keys(examMap || {}).some(cat => tagsOf(examMap, cat).some(t => t.startsWith(exam)));
}

/**
 * Набор галочек «готовлю к экзамену»: включены ровно типы с меткой этого
 * экзамена. Типы, которых нет в `keys`, не трогаются (их нет в разделе).
 */
export function categoriesForExam(keys, examMap, exam, current = {}) {
  const next = { ...current };
  for (const cat of keys) {
    next[cat] = tagsOf(examMap, cat).some(t => t.startsWith(exam));
  }
  return next;
}
