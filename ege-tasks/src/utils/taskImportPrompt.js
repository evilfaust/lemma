/**
 * Промпт для внешней ИИ под «Импорт задач» (TaskImporter, формат ЕГЭ).
 *
 * Отличие от «Импорта работы» (workImportFormat.buildAiPrompt): там работа с
 * вариантами и темой у каждой задачи, здесь — пачка задач ОДНОЙ темы в банк:
 * тема в шапке файла, задача — строка «**N** [сложность] условие», ответ —
 * ПОСЛЕ условия (его строка закрывает условие, см. markdownTaskParser).
 * Чертежи — та же шпаргалка редакторов (workImportDrawings), но картинку-
 * плейсхолдер этот импорт прикрепить не умеет: задача без чертежа получает
 * тег «нужен рисунок». Пример формата разбирает тест (taskImportPrompt.test.js).
 */

import { buildDrawingsPromptSection } from './workImportDrawings';

/** Тег задачи, рисунок которой ИИ текстом не перенесла. */
export const NEEDS_PICTURE_TAG = 'нужен рисунок';

/** Пример файла — показывается в промпте и проверяется тестом парсером. */
export const TASK_PROMPT_EXAMPLE = [
  '---',
  'topic: Планиметрия',
  'subtopic: Трапеция',
  'difficulty: 1',
  'source: Иванова Н.П., самостоятельная работа',
  'year: 2026',
  '---',
  '',
  '**1** [1] Основания трапеции равны $10$ и $4$. Найдите среднюю линию трапеции.',
  '',
  '```planim',
  'трапеция ABCD 10 4 4',
  'длина AD 10',
  'длина BC 4',
  '```',
  'ответ: 7',
  '',
  '**2** [2] Диагонали трапеции $ABCD$ пересекаются в точке $O$, $AD = 12$, $BC = 4$. Найдите $AO : OC$.',
  'ответ: 3',
  '',
  '**3** [1] Площадь участка на плане, изображённом на рисунке, …',
  'ответ: 24',
  `tags: [${NEEDS_PICTURE_TAG}]`,
];

/**
 * @param {object} params
 * @param {Array<{title, ege_number?, exam_type?}>} params.topics — темы базы
 * @param {string|null} [params.examType] — оставить темы одного экзамена
 * @param {boolean} [params.drawings=true] — учить модель переносить чертежи
 * @param {number} [params.maxTopics=400]
 * @returns {string}
 */
export function buildTaskImportPrompt({ topics = [], examType = null, drawings = true, maxTopics = 400 } = {}) {
  const filtered = examType ? topics.filter((t) => t.exam_type === examType) : topics;
  const list = filtered.slice(0, maxTopics).map((t) => `- ${t.title}${t.ege_number ? ` (№${t.ege_number})` : ''}`);
  const truncated = filtered.length > maxTopics;

  return [
    'Ты помогаешь перенести задачи по математике с фото/скана/PDF в текстовый формат для банка задач.',
    '',
    'Верни ОДИН markdown-файл строго по формату ниже. Без пояснений до и после, без ```-ограждений вокруг всего файла.',
    '',
    '=== ФОРМАТ ===',
    '',
    '---',
    'topic: <тема из списка ниже — одна на весь файл>',
    'subtopic: <подтема, если очевидна; иначе строку не пиши>',
    'difficulty: <1-5 — сложность по умолчанию>',
    'source: <откуда задачи: учебник, автор, сборник>',
    'year: <год, если известен>',
    'tags: [<общие теги через запятую, если нужны>]',
    '---',
    '',
    '**1** [<сложность 1-5>] <условие задачи>',
    '<продолжение условия: абзацы, таблицы, чертёж>',
    'ответ: <ответ>',
    '',
    '**2** [<сложность>] <условие>',
    'ответ: <ответ>',
    'tags: [<теги этой задачи, если нужны>]',
    '',
    '=== ПРАВИЛА ===',
    '',
    '1. Каждая задача начинается с новой строки «**номер** [сложность]» — номер жирным, сложность в квадратных скобках цифрой: 1 — базовая, 2 — средняя, 3 — повышенная, 4 — высокая, 5 — олимпиадная. Непонятно — ставь 1.',
    '2. Условие — всё после «**номер** [сложность]» до строки «ответ:». Можно писать абзацы (через пустую строку), списки «а) … б) …», таблицы markdown.',
    '3. «ответ:» — ОДНОЙ строкой ПОСЛЕ условия, как в бланке: число (десятичная дробь — через запятую: 0,5) или формула в $…$. Ответа на листке нет — строку «ответ:» не пиши, сам не решай.',
    '4. «tags:» — необязательная строка сразу после «ответ:».',
    '5. Формулы — в LaTeX внутри $…$ (KaTeX): дроби \\frac{a}{b}, корни \\sqrt{x}, степени x^{2}, индексы x_{0}, десятичные в формуле — $0{,}5$.',
    drawings
      ? '6. Чертёж/график/диаграмма/числовая прямая — блоком ```planim/```stereo/```plot/```chart/```numline внутри условия (до строки «ответ:»): когда что — в разделе «ЧЕРТЕЖИ». Словами чертёж не описывай.'
      : `6. Рисунки не переноси и словами не описывай: задаче с рисунком добавь строку «tags: [${NEEDS_PICTURE_TAG}]» — картинку добавят вручную.`,
    '7. Все задачи файла — ОДНОЙ темы. Тему бери ТОЛЬКО из списка ниже, копируя название точно; не подходит ни одна — напиши свою короткую тему, её создадут вручную. Если на листке задачи разных тем — верни только задачи главной темы.',
    '8. Решения не переноси — только условия и ответы. Нумерацию сохраняй как на листке.',
    '',
    'Пример:',
    '',
    ...TASK_PROMPT_EXAMPLE,
    '',
    ...(drawings ? [...buildDrawingsPromptSection({ fallback: 'tag' }), ''] : []),
    '=== ТЕМЫ В БАЗЕ ===',
    '',
    ...(list.length ? list : ['(список тем не передан — пиши свою короткую тему)']),
    ...(truncated ? ['', `(показаны первые ${maxTopics} тем из ${filtered.length})`] : []),
  ].join('\n');
}
