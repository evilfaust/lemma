// ── Проверка блоков при разборе ──────────────────────────────────────────────

const DRAWING_PARSERS = {
  planim: parsePlanimBlock,
  stereo: parseStereoBlock,
};

/**
 * Находит блоки ```planim / ```stereo в markdown.
 * @returns {{ kind: 'planim'|'stereo', text: string }[]}
 */
export function extractDrawingBlocks(md) {
  const blocks = [];
  const lines = String(md || '').split(/\r?\n/);
  let current = null;
  let fence = null;
  for (const line of lines) {
    const m = line.match(/^\s*(`{3,}|~{3,})\s*([a-zа-яё-]*)/i);
    if (m && !fence) {
      fence = m[1];
      const kind = m[2].toLowerCase();
      current = DRAWING_PARSERS[kind] ? { kind, lines: [] } : null;
      continue;
    }
    if (m && fence && m[1][0] === fence[0] && m[1].length >= fence.length && !m[2]) {
      if (current) blocks.push({ kind: current.kind, text: current.lines.join('\n') });
      current = null;
      fence = null;
      continue;
    }
    if (current) current.lines.push(line);
  }
  // Незакрытый блок markdown дочитывает до конца — проверяем так же.
  if (current) blocks.push({ kind: current.kind, text: current.lines.join('\n') });
  return blocks;
}

/**
 * Разбирает чертежи текста теми же парсерами, что рисуют их на сайте.
 * Ошибка строки чертёж не рушит (шаг пропускается), но учитель должен о ней
 * узнать до сохранения.
 *
 * @returns {{ count: number, kinds: string[], problems: { kind, line, command, message }[] }}
 */
export function checkDrawingBlocks(md) {
  const blocks = extractDrawingBlocks(md);
  const problems = [];
  for (const block of blocks) {
    const src = block.text.split('\n');
    const { errors = [] } = DRAWING_PARSERS[block.kind](block.text);
    if (!block.text.trim()) {
      problems.push({ kind: block.kind, line: 0, command: '', message: 'пустой чертёж' });
      continue;
    }
    for (const err of errors) {
      problems.push({
        kind: block.kind,
        line: err.line,
        command: (src[err.line - 1] || '').trim(),
        message: err.message,
      });
    }
  }
  return { count: blocks.length, kinds: blocks.map((b) => b.kind), problems };
}
