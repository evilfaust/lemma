// Команда шпаргалки опирается на точки, которых в пустом чертеже нет, —
// ставим перед ней подходящую фигуру, чтобы тест проверял саму команду.
function planimSample(cmd) {
  if (/^(треугольник|прямоугольный|равнобедренный|равносторонний|квадрат|прямоугольник|параллелограмм|ромб|трапеция|сетка)/.test(cmd)) return cmd;
  if (/^A = \(/.test(cmd)) return cmd;
  if (/окр\(O\)/.test(cmd)) return `O = (0; 0)\nокружность O 2\nC = (5; 0)\n${cmd}`;
  if (/^окружность/.test(cmd)) return `O = (0; 0)\nA = (2; 0)\n${cmd}`;
  if (/^(прямой угол AHB)/.test(cmd)) return `треугольник ABC 5 6 7\nH = высота C AB\n${cmd}`;
  if (/BH|скрыть O/.test(cmd)) return `треугольник ABC 5 6 7\nH = высота B AC\nO = AC ∩ BH\n${cmd}`;
  if (/ABCD|AC ∩ BD/.test(cmd)) return `квадрат ABCD 4\n${cmd}`;
  return `треугольник ABC 5 6 7\n${cmd}`;
}

function stereoSample(cmd) {
  if (/S ⊥/.test(cmd)) return `пирамида 4 4 5 S\n${cmd}`;
  if (/^(MN|сечение MNB|X = MN)/.test(cmd)) return `куб 4\nM на AA1 1:2\nN = середина CC1\n${cmd}`;
  return `куб 4\n${cmd}`;
}

