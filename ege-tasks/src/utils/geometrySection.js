/**
 * Раздел геометрической задачи: планиметрия или стереометрия
 * (`geometry_tasks.section`, GEOMETRY_TASKS_PLAN.md § 1).
 *
 * Чистая эвристика без сети. По ней один раз размечен банк МЦНМО
 * (≈4,1 тыс. стереозадач из 17,6 тыс.), и ею же редактор подсказывает
 * раздел новой задачи. Окончательно раздел ставит учитель.
 */

export const GEOMETRY_SECTIONS = [
  { value: 'planim', label: 'Планиметрия' },
  { value: 'stereo', label: 'Стереометрия' },
];

export const SECTION_LABELS = { planim: 'Планиметрия', stereo: 'Стереометрия' };

// JS-шный \b кириллицу буквой не считает — границы слов через lookbehind.
const L = 'а-яё';

// Фасет МЦНМО (объект/метод/факт) про пространство. Ложные срабатывания,
// найденные на банке: «Пере‑сечение», «полу‑плоскость», «координатная
// плоскость» — они отсечены.
const STEREO_TAG_RE = new RegExp(
  [
    '(?<!полу)(?<!координатной )плоскост', 'пространств', 'пирамид', 'призм',
    `(?<![${L}])куб`, 'тетраэдр', 'октаэдр', 'сфер', `(?<![${L}])шар`, 'конус',
    'цилиндр', 'параллелепипед', 'многогран', 'двугранн', 'трёхгранн',
    'четырёхгранн', 'скрещива', 'объём', `(?<![${L}])тел[аоу]?(?![${L}])`,
    'вращени', 'развёртк', 'поверхност', `(?<![${L}])сечени`, 'компланарн',
    `(?<![${L}])клин`, 'апофем', 'проектирован', 'трёх перпендикуляр',
    '^поворот относительно прямой$',
  ].join('|'),
  'i',
);

// Планиметрические фасеты, которые регулярка задела бы словом «плоскость».
const PLANIM_TAG_EXCEPTIONS = [
  /^расположение точек на плоскости относительно прямой$/i,
  /\(пространства\)/i, // «…M — произвольная точка плоскости (пространства)…»
];

// Сильные пространственные слова в условии — для задач без фасетов.
const STEREO_TEXT_RE = new RegExp(
  [
    'пирамид', 'призм', 'тетраэдр', 'параллелепипед', `(?<![${L}])сфер`, 'конус',
    'цилиндр', 'двугранн', 'трёхгранн', 'многогранн', 'октаэдр',
    `(?<![${L}])куб(?![${L}]*ическ)`, `(?<![${L}])шар(?![${L}]*нир)`,
    'скрещивающ', 'в пространстве', 'плоскостью', 'к плоскости',
    `(?<![${L}])р[её]бр`, `(?<![${L}])гран[ьиейя]`,
  ].join('|'),
  'i',
);

/** Фасет говорит о пространственной фигуре или приёме. */
export function isStereoTagName(name) {
  const s = String(name || '').trim();
  if (!s) return false;
  if (PLANIM_TAG_EXCEPTIONS.some((re) => re.test(s))) return false;
  return STEREO_TAG_RE.test(s);
}

/** В тексте условия есть явно пространственные слова. */
export function hasStereoWords(text) {
  return STEREO_TEXT_RE.test(String(text || ''));
}

/**
 * Угадать раздел задачи.
 * @param {{ statement?: string, tagNames?: string[], topicTitle?: string }} task
 * @returns {'planim'|'stereo'}
 */
export function guessGeometrySection({ statement = '', tagNames = [], topicTitle = '' } = {}) {
  const topic = String(topicTitle || '').toLowerCase();
  if (topic.includes('стереометр')) return 'stereo';
  if (topic.includes('планиметр')) return 'planim';
  if (tagNames.some(isStereoTagName)) return 'stereo';
  return hasStereoWords(statement) ? 'stereo' : 'planim';
}
